// Writes public/assets/data/manifest.js: the part of the content that is safe to publish (titles and counts, no questions,
// answers or lesson text). The home page and the pricing page build their lists from it; the real content comes from /api/content.
// Run after editing anything in content/:   npm run manifest
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const bank = require('../api/_bank.js');

const manifest = {
  counts: { grammar: bank.bank('grammar').length, conversations: bank.bank('conversations').length, extra: bank.bank('extra').length },
  cloze: bank.bank('cloze').map((p) => ({ topic: p.topic, blanks: p.blanks.length })),
  lessons: bank.lessons().map((l) => ({
    id: l.id, level: l.level, minutes: l.minutes, title: l.title, en: l.en, intro: l.intro, exerciseCount: l.exercises.length,
  })),
};

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'assets', 'data', 'manifest.js');
writeFileSync(out,
  '// GENERATED by scripts/build-manifest.mjs - do not edit. Titles and counts only; questions and answers are served by /api/content.\n' +
  'window.CEFR_DATA = window.CEFR_DATA || {};\n' +
  'window.CEFR_DATA.manifest = ' + JSON.stringify(manifest) + ';\n' +
  '// the lesson list, for pages that only need titles (lesson text and exercises are loaded one lesson at a time)\n' +
  'window.CEFR_DATA.lessons = window.CEFR_DATA.manifest.lessons;\n');
console.log('manifest.js written:', manifest.lessons.length, 'lessons,', manifest.cloze.length, 'cloze passages');
